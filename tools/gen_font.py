#: Printable ASCII (Phaser's RetroFont TEXT_SET1) plus our extras, in atlas order.
CHARS = ''.join(chr(c) for c in range(32, 127)) + '¥·✓—×'

MISSING = ['#####', '#...#', '#...#', '#...#', '#...#', '#...#', '#####']


def _draw_glyph(px, rows):
    for y, row in enumerate(rows):
        for x, ch in enumerate(row):
            if ch == '#':
                px[x, y] = WHITE


def build(out_png):
    rows = (len(CHARS) + CHARS_PER_ROW - 1) // CHARS_PER_ROW
    sheet = Image.new('RGBA', (CHARS_PER_ROW * CELL_W, rows * CELL_H), (0, 0, 0, 0))

    for i, ch in enumerate(CHARS):
        cell = new_image(CELL_W, CELL_H)
        _draw_glyph(cell.load(), G.get(ch, MISSING))
        paste_grid(sheet, cell, i, CHARS_PER_ROW, CELL_W, CELL_H)

    sheet.save(out_png)
    return {
        'chars': CHARS,
        'width': CELL_W,
        'height': CELL_H,
        'charsPerRow': CHARS_PER_ROW,
        # Keep (CELL_H + lineSpacing) EVEN. Phaser adds the spacing to every
        # line including the last, so this is the height of a one-line label -
        # and an odd height centred with a 0.5 origin draws on a half pixel.
        # With NEAREST sampling that does not blur the glyph, it samples the
        # next row of this atlas, which is a different character entirely.
        'lineSpacing': 2,
        'count': len(CHARS),
    }
